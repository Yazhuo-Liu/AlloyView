import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { crc32, createImageArchive, ImageArchiveBuilder } from '../src/export-archive.js';

test('ZIP stores intact image bytes with matching CRC and directory offsets', async () => {
  const bytes = new TextEncoder().encode('123456789');
  assert.equal(crc32(bytes), 0xcbf43926);
  const archive = new Uint8Array(await createImageArchive([{ name: 'frame-1.png', bytes }]).arrayBuffer());
  const view = new DataView(archive.buffer);
  const nameLength = view.getUint16(26, true);
  const directoryOffset = 30 + nameLength + bytes.length;
  assert.equal(view.getUint32(0, true), 0x04034b50);
  assert.equal(view.getUint32(14, true), 0xcbf43926);
  assert.deepEqual(archive.slice(30 + nameLength, directoryOffset), bytes);
  assert.equal(view.getUint32(directoryOffset, true), 0x02014b50);
  assert.equal(view.getUint32(directoryOffset + 42, true), 0);
  assert.equal(view.getUint32(archive.length - 22, true), 0x06054b50);
  assert.equal(view.getUint32(archive.length - 6, true), directoryOffset);
});

test('incremental records reproduce the previous ZIP bytes, including Unicode and empty images', async () => {
  const entries = [{ name: 'frame-1.png', bytes: new TextEncoder().encode('123456789') },
    { name: '第二张\\frame.png', bytes: Uint8Array.from({ length: 4101 }, (_, index) => (index * 31 + 7) & 255) },
    { name: 'blank.png', bytes: new Uint8Array() }];
  const builder = new ImageArchiveBuilder();
  for (const entry of entries) builder.add(entry);
  const bytes = new Uint8Array(await builder.finish().arrayBuffer());
  assert.equal(builder.count, 3);
  assert.equal(builder.size, bytes.length);
  // Generated by the previous release's STORE writer before changing it.
  assert.equal(createHash('sha256').update(bytes).digest('hex'), 'b5d4b113867575db04f7c68839fd496625bf4ac622a237e4fc38b7cd0d500139');
  assert.deepEqual(bytes, new Uint8Array(await createImageArchive(entries).arrayBuffer()));
});

test('each prepared record snapshots its PNG and finishing does not read changed source bytes', async () => {
  const builder = new ImageArchiveBuilder(), bytes = new TextEncoder().encode('123456789');
  builder.add({ name: 'frame.png', bytes });
  bytes.fill(0);
  const archive = new Uint8Array(await builder.finish().arrayBuffer());
  const view = new DataView(archive.buffer), nameLength = view.getUint16(26, true);
  assert.equal(view.getUint32(14, true), 0xcbf43926);
  assert.deepEqual(archive.slice(30 + nameLength, 30 + nameLength + bytes.length), new TextEncoder().encode('123456789'));
  builder.clear();
  assert.equal(builder.count, 0); assert.equal(builder.size, 22);
  assert.equal(builder.finish().size, 22, 'clear releases prepared Blob records and directory buffers');
});

test('archive budgets reject an entire next record before copying it and cancellation prevents finalization', () => {
  const builder = new ImageArchiveBuilder({ maxBytes: 200 });
  builder.add({ name: '1.png', bytes: new Uint8Array(40) });
  const size = builder.size;
  assert.throws(() => builder.add({ name: '2.png', bytes: new Uint8Array(40) }), /exceeds 256 MiB/);
  assert.equal(builder.count, 1); assert.equal(builder.size, size);
  const controller = new AbortController(); controller.abort();
  assert.throws(() => builder.add({ name: '3.png', bytes: new Uint8Array() }, { signal: controller.signal }), { name: 'AbortError' });
  assert.throws(() => builder.finish({ signal: controller.signal }), { name: 'AbortError' });
  assert.equal(builder.count, 1);
  for (const maxBytes of [0, 21, NaN, 22.5, 256 * 1024 ** 2 + 1]) assert.throws(() => new ImageArchiveBuilder({ maxBytes }), /byte budget/);
  const full = new ImageArchiveBuilder();
  for (let index = 0; index < 500; index++) full.add({ name: `${index}.png`, bytes: new Uint8Array() });
  assert.throws(() => full.add({ name: '501.png', bytes: new Uint8Array() }), /at most 500/);
  assert.equal(full.count, 500);
});

test('indexed CRC preserves checksums of offset views and deterministic binary inputs', () => {
  function reference(bytes) {
    let crc = 0xffffffff;
    for (const byte of bytes) {
      crc ^= byte;
      for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
    }
    return (crc ^ 0xffffffff) >>> 0;
  }
  const source = Uint8Array.from({ length: 4096 }, (_, index) => (index * 67 + (index >>> 3)) & 255);
  for (const bytes of [new Uint8Array(), source, source.subarray(17, 3011), source.subarray(4095)]) assert.equal(crc32(bytes), reference(bytes));
});
