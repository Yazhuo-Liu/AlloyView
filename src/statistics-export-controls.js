import { StatisticsExportClient } from './statistics-export-client.js';
import { completedResult } from './statistics-export.js';
import { downloadBlob } from './export-archive.js';

const EMPTY_SELECTION_GROUPS = Object.freeze({ groups: Object.freeze([]) });

export const STATISTICS_EXPORT_BUTTONS = Object.freeze({
  'export-statistics-summary': 'summary', 'export-property-statistics': 'properties',
  'export-categorical-populations': 'categories', 'export-coordination-distribution': 'coordination',
  'export-atom-properties': 'atoms', 'export-rdf': 'rdf', 'export-dxa-summary': 'dxa-summary',
  'export-dxa-lines': 'dxa-lines', 'export-bond-length-distribution': 'bond-length',
  'export-bond-angle-distribution': 'bond-angle', 'export-bond-order-statistics': 'bond-order',
  'export-bond-order-atoms': 'bond-order-atoms', 'export-voronoi-csv': 'voronoi-atoms',
  'export-voronoi-distributions': 'voronoi-distributions', 'export-voronoi-faces': 'voronoi-faces',
});

/** One controller covers statistics generated by CPU and GPU analyses. Getters
 * return completed results; refresh only reads their metadata, while exports
 * scan data in the persistent Worker. The optional onDownload facilitates
 * integration tests and alternative save interfaces. */
export function initializeStatisticsExports({ getFrame, getFileName = () => 'structure', getFrameIndex = () => getFrame()?.frameIndex ?? 0,
  getResults = () => ({}), getDxaNetwork = () => null, getSelectionGroups = () => EMPTY_SELECTION_GROUPS, getLegend = () => null,
  notify = () => {}, onDownload = downloadBlob, client = new StatisticsExportClient(), documentRoot = document } = {}) {
  let enabled = true, busy = false, disposed = false, lastFrame = null, key = null, signature = [], domainKeys = new Map();
  const bindings = [];
  const status = documentRoot.getElementById('statistics-export-status');

  function contextParts() {
    const original = getFrame();
    if (!original) return null;
    const allResults = { ...original.atomeyeResults, ...getResults() };
    const results = Object.fromEntries(['rdf', 'bonds', 'bondStatistics', 'voronoi', 'localShear', 'displacement', 'referenceStrain']
      .filter(name => allResults[name]).map(name => [name, allResults[name]?.result ?? allResults[name]]));
    const network = getDxaNetwork(), groups = getSelectionGroups(), legend = getLegend();
    const currentSignature = [original, getFileName(), getFrameIndex(), original.ids, original.types, original.positions, original.timestep,
      original.cell, original.typeLabels, network, groups?.groups ?? groups, ...Object.keys(results).flatMap(name => [name, results[name]?.result ?? results[name]]),
      legend?.property, legend?.title, legend?.minimum, legend?.maximum, legend?.unit,
      ...(original.properties ?? []).flatMap(property => [property, property.name, property.unit, property.data, property.categories, property.histogram, property.cspSummary])];
    if (currentSignature.length !== signature.length || currentSignature.some((entry, index) => !Object.is(entry, signature[index]))) {
      key = {}; signature = currentSignature; domainKeys = new Map();
    }
    return { original, results, network, groups, legend, key };
  }

  function collect(kind) {
    const parts = contextParts();
    if (!parts) return null;
    const { original, results, network, groups, legend } = parts;
    // Most exports share a compact result snapshot. Voronoi face CSR and the
    // potentially large list of index strings are copied only when their
    // respective detailed table is requested.
    const domain = ['voronoi-atoms', 'voronoi-faces', 'voronoi-distributions', 'dxa-lines', 'dxa-summary', 'rdf', 'bond-order', 'bond-order-atoms'].includes(kind)
      ? kind : ['bond-length', 'bond-angle'].includes(kind) ? 'bond-distributions' : 'statistics';
    if (!domainKeys.has(domain)) domainKeys.set(domain, {});
    const snapshotKey = domainKeys.get(domain);
    // Avoid transmitting job AbortControllers, rendering geometry, or DXA line
    // knots. This snapshot contains only the data used by the CSV tables.
    const detailedAtoms = ['statistics', 'voronoi-atoms', 'voronoi-faces', 'bond-order-atoms'].includes(domain);
    const frame = { atomCount: original.ids.length, ...(detailedAtoms ? { ids: original.ids, types: original.types, typeLabels: original.typeLabels } : {}),
      ...(domain === 'statistics' ? { positions: original.positions } : {}),
      cell: original.cell, timestep: original.timestep, frameIndex: original.frameIndex,
      properties: domain === 'statistics' ? (original.properties ?? []).map(property => ({ name: property.name, displayName: property.displayName, unit: property.unit,
        data: property.data, categories: property.categories, analysisKind: property.analysisKind, externalImportId: property.externalImportId,
        histogram: property.histogram, meanCoordination: property.meanCoordination, cspSummary: property.cspSummary,
        analysisCutoff: property.analysisCutoff, analysisMs: property.analysisMs, analysisEngine: property.analysisEngine,
        analysisGpuRequested: property.analysisGpuRequested })) : [] };
    const pick = (result, names) => Object.fromEntries(names.filter(name => result[name] !== undefined).map(name => [name, result[name]]));
    const metadata = ['elapsedMs', 'workerCount', 'engine', 'incomplete', 'matched', 'unmatched', 'coordinationMode', 'normalization',
      'meanMetric', 'averageCoordination', 'averageShear', 'mappingMode', 'minimumImage'];
    const exportResults = Object.fromEntries(Object.entries(results).map(([name, result]) => {
      if (['localShear', 'displacement', 'referenceStrain'].includes(name)) return [name, pick(result, metadata)];
      if (name === 'bonds') return [name, pick(result, [...metadata, 'count'])];
      if (name === 'voronoi') return [name, pick(result, [...metadata, 'statistics', 'summary', 'coordinationHistogram', 'volumeHistogram', 'faceAreaHistogram', 'indexCounts',
        ...(domain === 'voronoi-atoms' ? ['atomicVolume', 'voronoiSurfaceArea', 'voronoiCoordination', 'voronoiBoundaryFaces', 'voronoiMaxFaceOrder', 'voronoiIndices'] : []),
        ...(domain === 'voronoi-faces' ? ['faceOffsets', 'faceAreas', 'faceOrders', 'faceNeighbors', 'faceBoundary', 'faceAccepted'] : [])])];
      if (name === 'bondStatistics' && domain === 'bond-distributions') return [name, pick(result, ['lengthDistribution', 'angleDistribution'])];
      return [name, result];
    }).filter(([name]) => domain === 'statistics' || domain.startsWith('voronoi-') && name === 'voronoi'
      || domain.startsWith('bond-') && name === 'bondStatistics' || domain === 'rdf' && name === 'rdf'));
    return { original, key: snapshotKey, snapshot: { frame, results: exportResults,
      fileName: getFileName(), frameIndex: getFrameIndex(), selectionGroups: groups,
      legend: legend ? { property: legend.property, title: legend.title, minimum: legend.minimum, maximum: legend.maximum, unit: legend.unit } : null,
      dxaNetwork: network && (domain === 'statistics' || domain.startsWith('dxa-')) ? { counts: network.counts, familyLengths: network.familyLengths, totalLength: network.totalLength,
        density: network.density, volume: network.volume, segmentCount: network.segments?.length ?? network.segmentCount,
        ...(domain === 'dxa-lines' ? { segments: (network.segments ?? []).map(line => ({ id: line.id, familyId: line.familyId,
          family: line.family, length: line.length, burgersVector: line.burgersVector, spatialBurgersVector: line.spatialBurgersVector,
          structureType: line.structureType, clusterId: line.clusterId, isClosedLoop: line.isClosedLoop ?? line.closedLoop })) } : {}) } : null } };
  }

  function available(kind, snapshot) {
    if (!snapshot) return false;
    const properties = snapshot.frame.properties ?? [];
    if (kind === 'summary' || kind === 'categories' || kind === 'atoms') return true;
    if (kind === 'properties') return properties.some(property => !property.categories?.length);
    if (kind === 'coordination') return properties.some(property => ['coordination', 'bondCoordination', 'voronoiCoordination', 'bondOrderCoordination', 'bondStatisticsCoordination'].includes(property.name));
    if (kind.startsWith('dxa-')) return Boolean(snapshot.dxaNetwork);
    if (kind.startsWith('bond-')) return Boolean(completedResult(snapshot, 'bondStatistics'));
    if (kind.startsWith('voronoi-')) return Boolean(completedResult(snapshot, 'voronoi'));
    return Boolean(completedResult(snapshot, kind));
  }

  function refresh() {
    const frame = getFrame();
    const priorKey = key;
    if (frame !== lastFrame) { lastFrame = frame; key = null; signature = []; }
    const parts = contextParts(), snapshot = parts ? { frame, results: parts.results, dxaNetwork: parts.network } : null;
    if (key !== priorKey) void client.clearSnapshot().catch(() => {});
    for (const [id, kind] of Object.entries(STATISTICS_EXPORT_BUTTONS)) {
      const button = documentRoot.getElementById(id);
      if (button) button.disabled = disposed || busy || !enabled || !available(kind, snapshot);
    }
    if (!busy && !frame && status) status.textContent = 'Open a structure to export completed statistics as CSV.';
    return snapshot;
  }

  async function exportTable(kind) {
    if (disposed || busy || !enabled) return null;
    const context = collect(kind);
    if (!context || !available(kind, context.snapshot)) { notify('Calculate this analysis before exporting its statistics.'); return null; }
    busy = true;
    if (status) status.textContent = 'Preparing CSV…';
    refresh();
    try {
      const output = await client.export(context.snapshot, context.key, kind);
      if (disposed || !enabled || getFrame() !== context.original) {
        if (status) status.textContent = 'CSV export stopped because the structure or frame changed.';
        return null;
      }
      await onDownload(output.blob, output.filename);
      if (status) status.textContent = `Saved ${output.filename}.`;
      return output;
    } catch (error) {
      if (!disposed && error.name !== 'AbortError') { if (status) status.textContent = error.message; notify(error.message); }
      return null;
    } finally { busy = false; if (!disposed) refresh(); }
  }

  for (const [id, kind] of Object.entries(STATISTICS_EXPORT_BUTTONS)) {
    const button = documentRoot.getElementById(id);
    if (!button) continue;
    const listener = () => { void exportTable(kind); };
    button.addEventListener('click', listener); bindings.push([button, listener]);
  }
  refresh();
  return { refresh, exportTable, setEnabled(value) { enabled = Boolean(value); refresh(); },
    dispose() { disposed = true; for (const [button, listener] of bindings) button.removeEventListener('click', listener); client.dispose(); } };
}
