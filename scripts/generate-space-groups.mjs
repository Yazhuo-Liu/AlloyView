// Regenerate the synchronous CIF database from the pinned official moyo WASM.
import { readFile, writeFile } from 'node:fs/promises';
import { initSync, hall_symbol_entry, operations_from_number } from '../src/crystal/vendor/moyo/moyo_wasm.js';

initSync({ module: await readFile(new URL('../src/crystal/vendor/moyo/moyo_wasm_bg.wasm', import.meta.url)) });
const gcd = (a, b) => b ? gcd(b, a % b) : a;
function expression(operation) {
  return [0, 1, 2].map(axis => {
    const terms = [];
    for (let variable = 0; variable < 3; variable++) {
      const value = operation.rotation[axis + variable * 3];
      if (value) terms.push(`${value < 0 ? '-' : '+'}${Math.abs(value) === 1 ? '' : Math.abs(value)}${'xyz'[variable]}`);
    }
    const value = ((operation.translation[axis] % 1) + 1) % 1;
    const numerator = Math.round(value * 24);
    if (Math.abs(value - numerator / 24) > 1e-10) throw new Error('Unexpected noncrystallographic translation.');
    if (numerator) { const divisor = gcd(numerator, 24); terms.push(`+${numerator / divisor}/${24 / divisor}`); }
    return terms.join('').replace(/^\+/, '') || '0';
  }).join(',');
}
const entries = [];
for (let hall = 1; hall <= 530; hall++) {
  const entry = hall_symbol_entry(hall);
  entries.push([hall, entry.number, entry.setting, entry.hall_symbol.replaceAll('=', '"').replaceAll('^', "'"), entry.hm_short,
    entry.hm_full, operations_from_number(entry.number, { type: 'HallNumber', value: hall }, false).map(expression)]);
}
await writeFile(new URL('../src/crystal/space-group-data.js', import.meta.url),
  '// Generated by scripts/generate-space-groups.mjs from moyo 0.21.0 (MIT OR Apache-2.0).\n'
  + '// Entries: Hall number, IT number, setting, Hall symbol, short/full HM symbols, xyz operations.\n'
  + 'export const SPACE_GROUP_DATA = ' + JSON.stringify(entries) + ';\n');
