import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { ELEMENT_SYMBOLS } from '../src/data/chemical-elements.js';

// Reproducible offline extraction from the retained MPL-covered Source Code
// Form. Numeric values are not normalized, extrapolated or replaced by Z.
const root = resolve(import.meta.dirname, '..');
const electronPath = 'third_party/gemmi-diffraction/c4322.hpp';
const neutronPath = 'third_party/gemmi-diffraction/neutron92.hpp';
const destination = 'src/crystal/diffraction-scattering-data.js';
const electronSource = await readFile(resolve(root, electronPath), 'utf8');
const electronBlock = electronSource.split('typename C4322<Real>::Coef C4322<Real>::data[99] = {')[1]?.split('};')[0];
if (!electronBlock) throw new Error('The pinned Gemmi neutral electron table was not found.');
const electrons = [...electronBlock.matchAll(/\{([^}]+)\},\s*\/\/\s*([A-Z][a-z]?)(?:\s|$)/g)].map(([, values, symbol]) => {
  const coefficients = values.split(',').map(value => Number(value.trim()));
  if (coefficients.length !== 10 || coefficients.some(value => !Number.isFinite(value))
      || coefficients.slice(5).some(value => value <= 0)) {
    throw new Error(`Invalid electron coefficient row for ${symbol}.`);
  }
  return { symbol, coefficients };
});
if (electrons.length !== 98 || electrons.some((record, index) => record.symbol !== ELEMENT_SYMBOLS[index])) {
  throw new Error('Expected exactly the neutral elements H through Cf in the electron table.');
}
const neutronSource = await readFile(resolve(root, neutronPath), 'utf8');
const neutronBlock = neutronSource.split('Real Neutron92<Real>::data[121] = {')[1]?.split('};')[0];
if (!neutronBlock) throw new Error('The pinned Gemmi neutron table was not found.');
const neutrons = [...neutronBlock.matchAll(/\/\*([A-Za-z]+)\*\/\s*([+-]?[\d.]+)\s*[,\n]/g)]
  .map(([, symbol, value]) => ({ symbol, value: Number(value) }));
const neutronOrder = ['X', ...ELEMENT_SYMBOLS, 'D', 'END'];
if (neutrons.length !== 121 || neutrons.some((record, index) => record.symbol !== neutronOrder[index]
    || !Number.isFinite(record.value))) {
  throw new Error('Expected exactly the 121 pinned neutron rows, including pseudo-elements and deuterium.');
}
// In Gemmi Neutron92.has(), zero is an unavailable row, not a zero coherent
// length. Retain signed amplitudes and the explicit D isotope; omit unknowns.
const availableNeutrons = neutrons.filter(record => record.value !== 0);
const output = `/*! Copyright 2020, 2022 Global Phasing Ltd.
 * SPDX-License-Identifier: MPL-2.0
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/.
 */
//
// Electron C4322 and neutron Neutron92 values adapted from Gemmi v0.7.5,
// commit 5cc1c23c6007e0e6cbd69289c6f7c0bff50e943e.
// Generated by scripts/generate-diffraction-scattering.mjs; no invented values.
// Electron layout: a1..a5, b1..b5. fe(s) = sum(a_i exp(-b_i s²)), in Å.
export const ELECTRON_C4322_COEFFICIENTS = Object.freeze({
${electrons.map(({ symbol, coefficients }) => `  ${symbol}: Object.freeze(${JSON.stringify(coefficients)}),`).join('\n')}
});

// Real bound coherent neutron lengths in fm. Negative signs affect coherent
// interference. Missing zero-coded rows are deliberately absent. Values for
// radioactive elements use the source table's stated isotopic convention.
export const NEUTRON92_SCATTERING_LENGTHS = Object.freeze({
${availableNeutrons.map(({ symbol, value }) => `  ${symbol}: ${value},`).join('\n')}
});
`;
await writeFile(resolve(root, destination), output);
const files = [electronPath, neutronPath, 'licenses/Gemmi-MPL-2.0.txt', destination];
const checksums = await Promise.all(files.map(async path => `${createHash('sha256').update(await readFile(resolve(root, path))).digest('hex')}  ${path}`));
await writeFile(resolve(root, 'third_party/gemmi-diffraction/SHA256SUMS'), `${checksums.join('\n')}\n`);
console.log(`Generated ${electrons.length} electron records and ${availableNeutrons.length} nonzero neutron records from pinned Gemmi data.`);
