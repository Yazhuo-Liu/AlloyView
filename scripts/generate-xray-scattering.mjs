import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { ELEMENT_SYMBOLS } from '../src/data/chemical-elements.js';

// Reproducible offline extraction. The pinned upstream Source Code Form is
// retained so the MPL-covered numeric table and its adaptation are available.
const root = resolve(import.meta.dirname, '..');
const upstream = 'third_party/gemmi-it92/it92.hpp';
const destination = 'src/crystal/xray-scattering-data.js';
const source = await readFile(resolve(root, upstream), 'utf8');
const block = source.split('typename IT92<Real>::Coef IT92<Real>::data[99+112] = {')[1]?.split('// Atoms with charge')[0];
if (!block) throw new Error('The pinned Gemmi neutral scattering table was not found.');
const records = [...block.matchAll(/\{([^}]+)\},\s*\/\/\s*([A-Z][a-z]?)(?:\s|$)/g)].map(([, values, symbol]) => {
  const coefficients = values.split(',').map(value => Number(value.trim()));
  if (coefficients.length !== 9 || coefficients.some(value => !Number.isFinite(value))) throw new Error(`Invalid coefficient row for ${symbol}.`);
  return { symbol, coefficients };
});
if (records.length !== 98 || records.some((record, index) => record.symbol !== ELEMENT_SYMBOLS[index])) {
  throw new Error('Expected exactly the neutral elements H through Cf, in atomic-number order.');
}
const output = `/*! Copyright 2019 Global Phasing Ltd.
 * SPDX-License-Identifier: MPL-2.0
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/.
 */
//
// Neutral-atom International Tables (1992) Cromer–Mann coefficients adapted
// from Gemmi v0.7.5, commit 5cc1c23c6007e0e6cbd69289c6f7c0bff50e943e.
// Generated by scripts/generate-xray-scattering.mjs. Keep the upstream values;
// no atomic-number normalization or ionic/unknown-element fallback is applied.
// Layout: a1, a2, a3, a4, b1, b2, b3, b4, c.
export const XRAY_IT92_COEFFICIENTS = Object.freeze({
${records.map(({ symbol, coefficients }) => `  ${symbol}: Object.freeze(${JSON.stringify(coefficients)}),`).join('\n')}
});
`;
await writeFile(resolve(root, destination), output);
const files = [upstream, 'licenses/Gemmi-MPL-2.0.txt', destination];
const checksums = await Promise.all(files.map(async path => `${createHash('sha256').update(await readFile(resolve(root, path))).digest('hex')}  ${path}`));
await writeFile(resolve(root, 'third_party/gemmi-it92/SHA256SUMS'), `${checksums.join('\n')}\n`);
console.log(`Generated ${records.length} neutral-atom X-ray scattering records from pinned Gemmi data.`);
